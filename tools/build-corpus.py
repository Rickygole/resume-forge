#!/usr/bin/env python3
"""Bundle the verified corpus into public/corpus.js.

Only PUBLIC repo READMEs belong here: the site is deployed publicly. Private
repos (provenance-encoder, ghosted-gps) are deliberately excluded, so facts from
those projects must be supplied by hand in the extra-instructions box.

    python3 tools/build-corpus.py
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"
MASTER_PDF = pathlib.Path.home() / "Desktop" / "Ricky Gole CV.pdf"


def main():
    if MASTER_PDF.exists():
        subprocess.run(
            ["pdftotext", "-layout", str(MASTER_PDF), str(CORPUS / "master_cv.txt")],
            check=True,
        )
        print("refreshed master_cv.txt from", MASTER_PDF.name)

    master = (CORPUS / "master_cv.txt")
    if not master.exists():
        sys.exit("corpus/master_cv.txt missing and no master CV on the Desktop")

    sources = {p.stem: p.read_text(encoding="utf-8") for p in sorted(CORPUS.glob("*.md"))}
    payload = {"master_cv": master.read_text(encoding="utf-8"), "sources": sources}

    out = ROOT / "public" / "corpus.js"
    out.write_text(
        "// Generated by tools/build-corpus.py. Do not hand-edit.\n"
        "window.CORPUS = " + json.dumps(payload, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}  {out.stat().st_size/1024:.0f} KB  "
          f"({len(sources)} sources)")


if __name__ == "__main__":
    main()
